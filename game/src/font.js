function glyphFor(ch) {
  if (ch >= 'A' && ch <= 'Z') return ROWS[ch.charCodeAt(0) - 65];
  if (ch >= '0' && ch <= '9') return DIGITS[ch.charCodeAt(0) - 48];
  return MARKS[ch] ?? MARKS[' '];
}

// Normalise a string to what the font can draw.
export function fontText(text) {
  return String(text)
    .toUpperCase()
    .replace(/[—–]/g, '-')
    .replace(/…/g, '...')
    .replace(/[·•]/g, '.')
    .replace(/[’‘]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[^A-Z0-9 .,;:!?'"\-/()+=\n]/g, ' ');
}

export function textWidth(text, scale) {
  const clean = fontText(text);
  return clean.length * 6 * scale - scale;
}

// Draw text with its top-left corner at (x, y). `align` is left,
// center or right around x. Scale 1 = 5x7 pixels per glyph.
export function drawText(ctx, text, x, y, scale = 2, color = '#e8e6df', align = 'left') {
  const clean = fontText(text);
  const w = textWidth(clean, scale);
  let ox = x;
  if (align === 'center') ox = x - w / 2;
  else if (align === 'right') ox = x - w;
  ctx.fillStyle = color;
  let cx = ox;
  for (const ch of clean) {
    const glyph = glyphFor(ch);
    for (let r = 0; r < 7; r += 1) {
      for (let c = 0; c < 5; c += 1) {
        if (glyph[r][c] === '1') {
          ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale;
  }
}
